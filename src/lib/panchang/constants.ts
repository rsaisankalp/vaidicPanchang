// Moon Nivas based on moon's longitude quadrant (very simplified)
export function moonNivas(moonLon: number): string {
  // Each rashi-traya assigned a direction; this is approximate
  const idx = Math.floor((moonLon % 360) / 90) % 4;
  return MOON_NIVAS_HI[idx];
}
