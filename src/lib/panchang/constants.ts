// Karana derivation per Vedic rules (60 half-tithis in a lunar month).
// External API numbers them 1–11 by unique identity, not 1–60 by sequence:
//   Bava=1, Balava=2, Kaulava=3, Taitila=4, Gara=5, Vanija=6, Vishti=7,
//   Kimstughna=8, Shakuni=9, Chatushpada=10, Naga=11
// (Verified against gwala API output for Aug 15 2025: karan 8 = Vishti.)
//
// Wait — that's actually a different ordering. The API numbers in Aug 15 had
// karan_number=8 with karan_name=विष्टि. So the API uses: Bava=1..Vishti=7? No,
// Vishti would be 7. Yet returned 8. That suggests fixed-first ordering:
//   Kimstughna=1, Bava=2, Balava=3, Kaulava=4, Taitila=5, Gara=6, Vanija=7,
//   Vishti=8, Shakuni=9, Chatushpada=10, Naga=11.
const KARAN_UNIQUE_NAMES = [
  KARANA_FIXED_HI[0], // 1 Kimstughna
  KARANA_REPEATING_HI[0], // 2 Bava
  KARANA_REPEATING_HI[1], // 3 Balava
  KARANA_REPEATING_HI[2], // 4 Kaulava
  KARANA_REPEATING_HI[3], // 5 Taitila
  KARANA_REPEATING_HI[4], // 6 Gara
  KARANA_REPEATING_HI[5], // 7 Vanija
  KARANA_REPEATING_HI[6], // 8 Vishti
  KARANA_FIXED_HI[1], // 9 Shakuni
  KARANA_FIXED_HI[2], // 10 Chatushpada
  KARANA_FIXED_HI[3], // 11 Naga
];

export function karanaNameByIndex(karanaSeq0to59: number): string {
  // Returns Hindi name from sequence (0..59).
  if (karanaSeq0to59 === 0) return KARANA_FIXED_HI[0];
  if (karanaSeq0to59 === 57) return KARANA_FIXED_HI[1];
  if (karanaSeq0to59 === 58) return KARANA_FIXED_HI[2];
  if (karanaSeq0to59 === 59) return KARANA_FIXED_HI[3];
  return KARANA_REPEATING_HI[(karanaSeq0to59 - 1) % 7];
}

// Map sequence index (0..59) to unique karana_number (1..11) used by external API.
export function karanaUniqueNumber(karanaSeq0to59: number): number {
  if (karanaSeq0to59 === 0) return 1; // Kimstughna
  if (karanaSeq0to59 === 57) return 9; // Shakuni
  if (karanaSeq0to59 === 58) return 10; // Chatushpada
  if (karanaSeq0to59 === 59) return 11; // Naga
  // 1..56 are Bava(2)..Vishti(8) cycling
  return ((karanaSeq0to59 - 1) % 7) + 2;
}

